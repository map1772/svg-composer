export function instantiateManifest(manifest: CompositionManifest): SceneObjectModel[] {
  return manifest.objects.map((object) => ({
    ...object,
    id: `${manifest.id}-${object.id}-${crypto.randomUUID()}`,
    presetObjectId: object.id,
    flipX: object.flipX ?? false,
  }));
}

export function findPreset(id: string) {
  return compositionPresets.find((preset) => preset.id === id);
}
